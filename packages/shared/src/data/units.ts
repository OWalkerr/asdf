/**
 * Birim tipleri (GDD §7). `id` snapshot'ta 8 bit olarak taşınır ve render tarafında
 * birim tipi başına InstancedMesh seçimi için kullanılır.
 *
 * Sayılar veri tanımıdır (metre, saniye); sim bunları yüklerken fxFromFloat / tamsayı
 * tick'e çevirir — bu dönüşümler (Math.round) tüm motorlarda aynıdır.
 * Phase 1: Helm's Deep çekirdek kadrosu.
 */
export type Faction = 'gondor' | 'rohan' | 'isengard' | 'mordor';
export type ArmorClass = 'light' | 'medium' | 'heavy' | 'cavalry' | 'monster' | 'structure' | 'siege';
export type DamageType = 'slash' | 'pierce' | 'spear' | 'crush' | 'siege' | 'fire' | 'magic';
/** Saldırı animasyon stili: kılıç savurma, mızrak dürtme, yay germe. */
export type AttackStyle = 'slash' | 'thrust' | 'bow';

export interface UnitDef {
  id: number;
  key: string;
  name: string;
  faction: Faction;
  /** Yürüme hızı (m/s). */
  speed: number;
  /** Asker başı can. */
  hp: number;
  armor: ArmorClass;
  attackStyle: AttackStyle;
  /** Asker başı vuruş hasarı ve tipi (GDD §7). */
  damage: number;
  damageType: DamageType;
  /** Saldırı aralığı (s). */
  attackInterval: number;
  /** Yakın dövüş erişimi veya menzil (m). */
  range: number;
  ranged: boolean;
  /** Tabur başına asker (GDD §6.1). */
  battalionSize: number;
  /** Tabur maliyeti (altın) ve kışlada yetiştirme süresi (s). Düşman için ödül tabanı. */
  cost: number;
  trainTime: number;
  /** Tercih edilen ön cephe genişliği (asker); dar geçitte otomatik daralır. */
  files: number;
  /** Formasyon aralığı (m). */
  spacing: number;
  /** Yuva sapması (m): Orc sürüleri düzensiz, Uruk/Gondor disiplinli (GDD §3.3). */
  jitter: number;
  /** Kuşatma aracı: yalnızca kapı/yapı hedefler, birliklerle çatışmaya girmez. */
  siegeOnly?: boolean;
  /** Kahraman (GDD §8): tek kişilik tabur, liderlik aurası ve yetenekler. */
  hero?: boolean;
  /** Düşman boss'u (dalgayla gelir): kendi takımına liderlik aurası verir, oyuncu çağıramaz. */
  boss?: boolean;
  /** Büyüyle çağrılan geçici birlik (kışlada yetiştirilmez, ödül/XP vermez). */
  summoned?: boolean;
  /** Süvari hücumu: çatışmaya girmez, geçtiği yoldaki düşmanları çiğner (trample). */
  charger?: boolean;
  /** Hasar almaz (Ölüler Ordusu). */
  invulnerable?: boolean;
  /** Yürüme/dörtnal adım frekansı (Hz, render). */
  stepRate?: number;
  /** TD: çıkışa ulaşan tabur başına kaybedilen can (varsayılan 1). */
  lifeCost?: number;
  /** Yakın dövüş vuruşu hedefin çevresine de yayılır (yarıçap m; Trol). */
  cleave?: number;
  /** Okçu birliği yapılara da ok atar (yapılara karşı hasar tipi: ateşli ok). */
  siegeArcher?: boolean;
  /** Alev püskürtme (Ateş Ejderi): menzilli saldırı hedef noktasına `aoe` m yarıçaplı ateş topu. */
  breath?: { aoe: number };
  /** Kuşatma kulesi: sura yanaşır, geniş geçit açar ve içindeki Uruk taburunu indirir. */
  siegeTower?: boolean;
  /** Kuşatma merdiveni taşır: sura dayar, düşman surun üstünden geçer. */
  ladder?: boolean;
  /** Ateş aurası (Balrog): her saniye `radius` içindeki düşmanlara `damage` ateş hasarı. */
  fireAura?: { radius: number; damage: number };
}

